import { describe, it, expect, vi } from "vitest";
import { render, screen } from "@testing-library/react";
import React from "react";
import { IdeasTab } from "../src/components/tabs/IdeasTab";
import { IdeasPlan } from "../src/types";

const mockFallbackIdeas: IdeasPlan = {
  overview_summary: "A customized Royal/Palace celebration curated for Pune (Metro).",
  themes_and_decor: [
    "Royal look on a budget in Pune: Rented vintage brass urlis with floating local marigolds.",
    "Heritage haveli aesthetic on a budget: Golden velvet shamiana fabric draping.",
  ],
  catering_and_menu: ["Royal feast on a budget: Signature regional royal thali prepared by local halwais."],
  function_activities: [{ function: "Wedding", activity: "Royal look on a budget: Varmala exchange." }],
  guest_experience_ideas: ["Welcome hospitality pouch with localized savory snacks."],
  money_saving_hacks: ["Trimming just 30 guests from your current 300 guest list saves approximately ₹28,795."],
  ideas_source: "fallback",
  budget_band: "Tight",
  budget_band_note: "Ideas are matched to your ₹2,133 per-guest budget (Tight) and your Royal/Palace vibe.",
};

const mockGeminiIdeas: IdeasPlan = {
  ...mockFallbackIdeas,
  ideas_source: "gemini",
};

describe("IdeasTab Component", () => {
  it("renders honest label for fallback rule-based ideas", () => {
    render(
      <IdeasTab
        ideasPlan={mockFallbackIdeas}
        city="pune"
        cityTier="Metro"
        totalBudget={640000}
        guestCount={300}
        functions={["Wedding"]}
        style="Royal/Palace"
        priorities={["Food"]}
        onIdeasUpdated={vi.fn()}
      />
    );

    expect(screen.getByText("Smart rule-based ideas (AI unavailable or not configured)")).toBeInTheDocument();
  });

  it("renders honest label for Gemini AI-generated ideas", () => {
    render(
      <IdeasTab
        ideasPlan={mockGeminiIdeas}
        city="Pune"
        cityTier="Metro"
        totalBudget={640000}
        guestCount={300}
        functions={["Wedding"]}
        style="Royal/Palace"
        priorities={["Food"]}
        onIdeasUpdated={vi.fn()}
      />
    );

    expect(screen.getByText("AI-generated by Gemini")).toBeInTheDocument();
  });

  it("renders the budget-band alignment line at top of Ideas tab", () => {
    render(
      <IdeasTab
        ideasPlan={mockFallbackIdeas}
        city="pune"
        cityTier="Metro"
        totalBudget={640000}
        guestCount={300}
        functions={["Wedding"]}
        style="Royal/Palace"
        priorities={["Food"]}
        onIdeasUpdated={vi.fn()}
      />
    );

    expect(
      screen.getByText(/Ideas are matched to your ₹2,133 per-guest budget \(Tight\) and your Royal\/Palace vibe\./i)
    ).toBeInTheDocument();
  });

  it("renders title-cased city name even when provided lowercase", () => {
    render(
      <IdeasTab
        ideasPlan={mockFallbackIdeas}
        city="navi mumbai"
        cityTier="Metro"
        totalBudget={640000}
        guestCount={300}
        functions={["Wedding"]}
        style="Royal/Palace"
        priorities={["Food"]}
        onIdeasUpdated={vi.fn()}
      />
    );

    expect(screen.getByText(/Navi Mumbai/i)).toBeInTheDocument();
  });

  it("renders consistent bullets and bold labels across idea groups and activities", () => {
    const { container } = render(
      <IdeasTab
        ideasPlan={mockFallbackIdeas}
        city="Pune"
        cityTier="Tier-2"
        totalBudget={1500000}
        guestCount={200}
        functions={["Wedding"]}
        style="Royal/Palace"
        priorities={["Food"]}
        onIdeasUpdated={vi.fn()}
      />
    );

    // All idea cards must have bullet points
    const bullets = container.querySelectorAll(".bullet-point");
    expect(bullets.length).toBeGreaterThanOrEqual(5);

    // Bold labels should exist for items with colons
    const strongLabels = container.querySelectorAll(".idea-item strong");
    expect(strongLabels.length).toBeGreaterThanOrEqual(3);

    // Activity should have Wedding: in bold followed by activity text
    expect(screen.getByText(/Wedding:/i)).toBeInTheDocument();
  });
});
