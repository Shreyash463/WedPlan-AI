import React, { useState, useRef, Suspense, lazy } from "react";
import {
  BudgetPlan,
  IdeasPlan,
  PlanFormInput,
  PlanResponse,
} from "../types";
import { formatCurrencyINR, formatDateReadable } from "../utils/formatters";

// Code-split tabs with React.lazy
const OverviewTab = lazy(() =>
  import("./tabs/OverviewTab").then((m) => ({ default: m.OverviewTab }))
);
const BudgetTab = lazy(() =>
  import("./tabs/BudgetTab").then((m) => ({ default: m.BudgetTab }))
);
const TimelineTab = lazy(() =>
  import("./tabs/TimelineTab").then((m) => ({ default: m.TimelineTab }))
);
const VendorsTab = lazy(() =>
  import("./tabs/VendorsTab").then((m) => ({ default: m.VendorsTab }))
);
const IdeasTab = lazy(() =>
  import("./tabs/IdeasTab").then((m) => ({ default: m.IdeasTab }))
);

interface DashboardProps {
  initialPlan: PlanResponse;
  formData: PlanFormInput;
  onEditDetails: () => void;
}

type TabKey = "overview" | "budget" | "timeline" | "vendors" | "ideas";

interface TabItem {
  key: TabKey;
  label: string;
  icon: string;
}

const TABS: TabItem[] = [
  { key: "overview", label: "Overview", icon: "📊" },
  { key: "budget", label: "Budget & What-If", icon: "💰" },
  { key: "timeline", label: "Timeline", icon: "📅" },
  { key: "vendors", label: "Vendors", icon: "🤝" },
  { key: "ideas", label: "Personalized Ideas", icon: "✨" },
];

export const Dashboard: React.FC<DashboardProps> = ({
  initialPlan,
  formData,
  onEditDetails,
}) => {
  const [activeTab, setActiveTab] = useState<TabKey>("overview");
  const [plan, setPlan] = useState<PlanResponse>(initialPlan);
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  const tabListRef = useRef<HTMLDivElement>(null);

  const showToast = (msg: string) => {
    setToastMessage(msg);
    setTimeout(() => {
      setToastMessage(null);
    }, 3000);
  };

  // Keyboard navigation for WAI-ARIA tablist (Left, Right, Home, End)
  const handleKeyDown = (e: React.KeyboardEvent, index: number) => {
    let newIndex: number;
    if (e.key === "ArrowRight") {
      newIndex = (index + 1) % TABS.length;
    } else if (e.key === "ArrowLeft") {
      newIndex = (index - 1 + TABS.length) % TABS.length;
    } else if (e.key === "Home") {
      newIndex = 0;
    } else if (e.key === "End") {
      newIndex = TABS.length - 1;
    } else {
      return;
    }

    e.preventDefault();
    const nextTab = TABS[newIndex].key;
    setActiveTab(nextTab);

    // Focus the new tab element
    const tabButtons = tabListRef.current?.querySelectorAll<HTMLButtonElement>(
      '[role="tab"]'
    );
    if (tabButtons && tabButtons[newIndex]) {
      tabButtons[newIndex].focus();
    }
  };

  const handlePrint = () => {
    window.print();
  };

  const handleCopyAsText = async () => {
    const textLines = [
      `=====================================================`,
      `WEDPLAN AI - INDIAN WEDDING PLAN`,
      `=====================================================`,
      `Event: ${plan.overview.couple_name || "Wedding Celebration"}`,
      `Date: ${formatDateReadable(plan.overview.wedding_date)} (${plan.overview.days_remaining} days remaining)`,
      `Location: ${plan.overview.city} (${plan.overview.city_tier})`,
      `Guests: ${plan.overview.guest_count} | Total Budget: ${formatCurrencyINR(plan.budget.total_budget)}`,
      `Budget Health: ${plan.budget.health_status} (${formatCurrencyINR(plan.budget.cost_per_guest)} / guest)`,
      ``,
      `--- BUDGET ALLOCATION ---`,
      ...plan.budget.allocations.map(
        (a) => `• ${a.category}: ${formatCurrencyINR(a.amount)} (${a.percentage.toFixed(1)}%)`
      ),
      ``,
      `--- TIMELINE KEY PHASES ---`,
      ...plan.timeline.tasks.slice(0, 10).map((t) => `• [${t.phase}] ${t.title} (Due: ${t.due_date})`),
      ``,
      `--- VENDOR CONTACT CHECKLIST ---`,
      ...plan.vendors.categories.map(
        (v) => `• ${v.name}: Budget ${formatCurrencyINR(v.allocated_budget)} | Lead time: ${v.lead_time_weeks} wks`
      ),
      ``,
      `--- PERSONALIZED THEMES & IDEAS ---`,
      ...plan.ideas.themes_and_decor.map((td) => `• Theme: ${td}`),
      ...plan.ideas.money_saving_hacks.map((h) => `• Money-saving tip: ${h}`),
      ``,
      `Generated by WedPlan AI (https://wedplan.ai)`,
      `Disclaimer: ${plan.disclaimer}`,
    ];

    try {
      await navigator.clipboard.writeText(textLines.join("\n"));
      showToast("Plan copied to clipboard as text! 📋");
    } catch {
      showToast("Unable to copy to clipboard.");
    }
  };

  const updateBudget = (newBudget: BudgetPlan) => {
    setPlan((prev) => ({
      ...prev,
      budget: newBudget,
      overview: {
        ...prev.overview,
        total_budget: newBudget.total_budget,
        guest_count: newBudget.guest_count,
        cost_per_guest: newBudget.cost_per_guest,
        health_status: newBudget.health_status,
        key_warnings: newBudget.warnings,
      },
    }));
  };

  const updateIdeas = (newIdeas: IdeasPlan) => {
    setPlan((prev) => ({
      ...prev,
      ideas: newIdeas,
    }));
    showToast("Wedding ideas refreshed! ✨");
  };

  return (
    <div className="dashboard-container">
      {/* Toast Alert */}
      {toastMessage && (
        <div className="toast-msg" role="status" aria-live="polite">
          {toastMessage}
        </div>
      )}

      {/* Dashboard Top Header & Actions Card */}
      <section className="dashboard-header-card" aria-label="Dashboard Overview">
        <div className="dashboard-title-group">
          <h1>
            {plan.overview.couple_name
              ? `${plan.overview.couple_name}'s Wedding Plan`
              : "Your Personalized Wedding Plan"}
          </h1>
          <div className="dashboard-subtitle">
            {formatDateReadable(plan.overview.wedding_date)} &bull;{" "}
            {plan.overview.city} &bull; {plan.overview.guest_count} Guests &bull;{" "}
            {formatCurrencyINR(plan.budget.total_budget)}
          </div>
        </div>

        <div className="dashboard-actions">
          <button
            type="button"
            className="btn btn-secondary"
            onClick={onEditDetails}
            aria-label="Edit intake form details"
          >
            ✏️ Edit Details
          </button>
          <button
            type="button"
            className="btn btn-secondary"
            onClick={handleCopyAsText}
            aria-label="Copy entire wedding plan as plain text"
          >
            📋 Copy Plan
          </button>
          <button
            type="button"
            className="btn btn-primary"
            onClick={handlePrint}
            aria-label="Print or download wedding plan as PDF"
          >
            🖨️ Download / Print
          </button>
        </div>
      </section>

      {/* Tablist with Arrow-Key Keyboard Navigation */}
      <nav aria-label="Wedding Planning Sections" className="tabs-navigation-wrapper">
        <div
          ref={tabListRef}
          role="tablist"
          aria-label="Planning Sections"
          className="tab-list"
        >
          {TABS.map((tab, idx) => {
            const isSelected = activeTab === tab.key;
            return (
              <button
                key={tab.key}
                role="tab"
                id={`tab-${tab.key}`}
                aria-selected={isSelected}
                aria-controls={`panel-${tab.key}`}
                tabIndex={isSelected ? 0 : -1}
                className="tab-btn"
                onClick={() => setActiveTab(tab.key)}
                onKeyDown={(e) => handleKeyDown(e, idx)}
              >
                <span aria-hidden="true">{tab.icon}</span>
                <span>{tab.label}</span>
              </button>
            );
          })}
        </div>
      </nav>

      {/* Tab Panels */}
      <Suspense
        fallback={
          <div style={{ padding: "40px", textAlign: "center", color: "var(--color-primary)" }}>
            Loading section...
          </div>
        }
      >
        {/* 1. Overview Tab Panel */}
        <div
          role="tabpanel"
          id="panel-overview"
          aria-labelledby="tab-overview"
          tabIndex={0}
          className={`tab-panel ${activeTab === "overview" ? "active" : ""}`}
          hidden={activeTab !== "overview"}
        >
          {activeTab === "overview" && (
            <OverviewTab
              overview={plan.overview}
              disclaimer={plan.disclaimer}
            />
          )}
        </div>

        {/* 2. Budget Tab Panel */}
        <div
          role="tabpanel"
          id="panel-budget"
          aria-labelledby="tab-budget"
          tabIndex={0}
          className={`tab-panel ${activeTab === "budget" ? "active" : ""}`}
          hidden={activeTab !== "budget"}
        >
          {activeTab === "budget" && (
            <BudgetTab
              budgetPlan={plan.budget}
              city={formData.city}
              cityTier={formData.city_tier}
              weddingDate={formData.wedding_date}
              functions={formData.functions}
              style={formData.style}
              initialPriorities={formData.priorities}
              onBudgetUpdated={updateBudget}
            />
          )}
        </div>

        {/* 3. Timeline Tab Panel */}
        <div
          role="tabpanel"
          id="panel-timeline"
          aria-labelledby="tab-timeline"
          tabIndex={0}
          className={`tab-panel ${activeTab === "timeline" ? "active" : ""}`}
          hidden={activeTab !== "timeline"}
        >
          {activeTab === "timeline" && (
            <TimelineTab timelinePlan={plan.timeline} />
          )}
        </div>

        {/* 4. Vendors Tab Panel */}
        <div
          role="tabpanel"
          id="panel-vendors"
          aria-labelledby="tab-vendors"
          tabIndex={0}
          className={`tab-panel ${activeTab === "vendors" ? "active" : ""}`}
          hidden={activeTab !== "vendors"}
        >
          {activeTab === "vendors" && (
            <VendorsTab vendorPlan={plan.vendors} />
          )}
        </div>

        {/* 5. Ideas Tab Panel */}
        <div
          role="tabpanel"
          id="panel-ideas"
          aria-labelledby="tab-ideas"
          tabIndex={0}
          className={`tab-panel ${activeTab === "ideas" ? "active" : ""}`}
          hidden={activeTab !== "ideas"}
        >
          {activeTab === "ideas" && (
            <IdeasTab
              ideasPlan={plan.ideas}
              city={formData.city}
              cityTier={formData.city_tier}
              totalBudget={plan.budget.total_budget}
              guestCount={plan.budget.guest_count}
              functions={formData.functions}
              style={formData.style}
              priorities={formData.priorities}
              specialRequests={formData.special_requests}
              onIdeasUpdated={updateIdeas}
            />
          )}
        </div>
      </Suspense>
    </div>
  );
};
