import React from "react";
import { CityTier, WeddingStyle } from "../../types";
import { RefreshIcon, SparklesIcon } from "../../components/common/Icons";

interface IdeasTopBarProps {
  ideasSource: string;
  style: WeddingStyle;
  cleanCity: string;
  cityTier: CityTier;
  isRegenerating: boolean;
  onRegenerate: () => void;
}

export const IdeasTopBar: React.FC<IdeasTopBarProps> = ({
  ideasSource,
  style,
  cleanCity,
  cityTier,
  isRegenerating,
  onRegenerate,
}) => {
  return (
    <div className="ideas-top-bar">
      <div className="ideas-meta-badge-group">
        <span
          className={`ideas-source-badge ${
            ideasSource === "gemini" ? "gemini" : "fallback"
          }`}
        >
          <SparklesIcon size={14} />
          {ideasSource === "gemini"
            ? "AI-generated by Gemini"
            : "Smart rule-based ideas (AI unavailable or not configured)"}
        </span>
        <span className="ideas-vibe-tag">
          Vibe: <strong>{style}</strong> • {cleanCity} ({cityTier})
        </span>
      </div>

      <button
        type="button"
        className="btn btn-secondary refresh-btn"
        onClick={onRegenerate}
        disabled={isRegenerating}
        aria-label="Refresh ideas"
      >
        <RefreshIcon size={16} className={isRegenerating ? "spinning" : ""} />
        <span>{isRegenerating ? "Refreshing Ideas..." : "Refresh Concepts"}</span>
      </button>
    </div>
  );
};
